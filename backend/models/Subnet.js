const { DataTypes } = require('sequelize');
const { sequelize } = require('../db');

/** 网段 ID 生成函数 */
const genSubnetId = () => {
  const ts = Date.now().toString(36).toUpperCase();
  let rnd = '';
  for (let i = 0; i < 6; i++) {
    rnd += Math.floor(Math.random() * 36).toString(36).toUpperCase();
  }
  return `SUBNET${ts}${rnd}`;
};

/**
 * Subnet 网段模型
 * 支持无限父子嵌套 + IPv4 / IPv6 双栈
 */
const Subnet = sequelize.define(
  'Subnet',
  {
    subnetId: {
      type: DataTypes.STRING,
      primaryKey: true,
      allowNull: false,
      unique: true,
      defaultValue: genSubnetId,
    },
    name: {
      type: DataTypes.STRING(200),
      allowNull: false,
      comment: '网段名称',
    },
    /** 地址族版本：ipv4 / ipv6 */
    ipVersion: {
      type: DataTypes.ENUM('ipv4', 'ipv6'),
      allowNull: false,
      defaultValue: 'ipv4',
      comment: '地址族：ipv4 / ipv6',
    },
    cidr: {
      type: DataTypes.STRING(80),
      allowNull: false,
      comment: 'CIDR 表示，如 192.168.1.0/24 或 2001:db8::/32',
    },
    networkAddress: {
      type: DataTypes.STRING(80),
      allowNull: false,
      comment: '网络地址',
    },
    broadcastAddress: {
      type: DataTypes.STRING(80),
      allowNull: true,
      comment: '广播地址（IPv6 用前缀末地址代替）',
    },
    netmask: {
      type: DataTypes.STRING(50),
      allowNull: true,
      comment: '子网掩码（IPv6 不使用）',
    },
    prefixLength: {
      type: DataTypes.INTEGER,
      allowNull: false,
      comment: '前缀长度（IPv4: 8~32，IPv6: 0~128）',
    },
    /** 网段范围（用 DECIMAL 存 128 位整数，兼容 IPv4 和 IPv6） */
    startInt: {
      type: DataTypes.DECIMAL(39, 0),
      allowNull: false,
      defaultValue: 0,
      comment: '网段起始地址整数（DECIMAL 存 128 位）',
    },
    endInt: {
      type: DataTypes.DECIMAL(39, 0),
      allowNull: false,
      defaultValue: 0,
      comment: '网段结束地址整数',
    },
    /** 主机数（字符串避免 JavaScript Number 精度丢失，IPv6 /64 开始数量极大） */
    totalHosts: {
      type: DataTypes.STRING(50),
      allowNull: true,
      comment: '总主机数（字符串，避免精度丢失）',
    },
    usableHosts: {
      type: DataTypes.STRING(50),
      allowNull: true,
      comment: '可用主机数',
    },
    gateway: {
      type: DataTypes.STRING(80),
      allowNull: true,
      comment: '网关地址',
    },
    dns: {
      type: DataTypes.JSON,
      defaultValue: [],
      allowNull: true,
    },
    vlanId: {
      type: DataTypes.STRING(50),
      allowNull: true,
    },
    autoGenerated: {
      type: DataTypes.BOOLEAN,
      defaultValue: true,
      comment: '是否已自动生成 IP 记录（IPv6 恒为 false）',
    },
    parentId: {
      type: DataTypes.STRING,
      allowNull: true,
    },
    /** 网段默认用途，网段内新建 IP 绑定时自动推荐 ipType */
    purpose: {
      type: DataTypes.ENUM('management', 'business', 'public', 'storage', 'other'),
      allowNull: true,
    },
    description: {
      type: DataTypes.TEXT,
      allowNull: true,
    },
  },
  {
    tableName: 'subnets',
    timestamps: true,
    indexes: [
      { fields: ['ipVersion'] },
      { fields: ['parentId'] },
      { fields: ['cidr'] },
      { fields: ['ipVersion', 'startInt', 'endInt'] },
      { fields: ['networkAddress', 'prefixLength'], unique: true, name: 'subnets_network_prefix_unique' },
      { fields: ['createdAt'] },
    ],
  }
);

module.exports = Subnet;
